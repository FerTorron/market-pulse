// research/STORY.template{,.en}.md + data/processed/market-data.json → research/STORY{,.en}.md
// Se niega a generar si la validación no pasó, salvo --allow-incomplete, que agrega un aviso visible arriba.
// Con --check solo controla las plantillas (dígitos a mano, marcadores, aserciones) sin escribir nada.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PATHS } from './lib/config.ts';
import { LOCALES } from './lib/render.ts';
import { REPO_ROOT, assertBlock, buildStory, getDataStatus, readTemplate } from './lib/story.ts';

const allowIncomplete = process.argv.includes('--allow-incomplete');
const checkOnly = process.argv.includes('--check');

const BANNER = {
  es: (m: string) => `> ⚠️ **BORRADOR CON DATOS INCOMPLETOS.** La validación no pasó: ${m}. No usar para publicar.\n\n`,
  en: (m: string) => `> ⚠️ **DRAFT WITH INCOMPLETE DATA.** Validation did not pass: ${m}. Do not publish.\n\n`,
};
const FOOTER = {
  es: (d: string) => `\n\n---\n<sub>Generado por \`scripts/render-story.ts\` desde \`data/processed/market-data.json\` (datos descargados ${d}). Ninguna cifra de mercado de este documento fue escrita a mano.</sub>\n`,
  en: (d: string) => `\n\n---\n<sub>Generated by \`scripts/render-story.ts\` from \`data/processed/market-data.json\` (data downloaded ${d}). No market figure in this document was written by hand.</sub>\n`,
};

try {
  if (assertBlock(readTemplate('es')) !== assertBlock(readTemplate('en'))) {
    throw new Error('El bloque <!-- assert --> de la plantilla en inglés no es idéntico al de la española.');
  }
  const stories = Object.fromEntries(LOCALES.map((l) => [l, buildStory(l)]));
  if (checkOnly) {
    console.log(`Plantillas OK (${LOCALES.join(', ')}): sin números escritos a mano, marcadores y aserciones resuelven.`);
    process.exit(0);
  }
  const status = getDataStatus();
  if (status.crossCheckFlagged.length) {
    console.error(`cross-check.json tiene diferencias con Yahoo fuera de tolerancia en: ${status.crossCheckFlagged.join(', ')}. La sección "Control" de la historia diría algo falso: revisar y reescribirla antes de generar.`);
    process.exit(1);
  }
  if (!status.validationPassed && !allowIncomplete) {
    console.error('La validación no pasó (data/processed/validation-report.json). No se genera STORY.md.');
    console.error('Errores:', status.errors.join(' | '));
    console.error('Para generar un borrador marcado como incompleto: pnpm render --allow-incomplete');
    process.exit(1);
  }
  for (const l of LOCALES) {
    let story = stories[l]!;
    if (!status.validationPassed) story = BANNER[l](JSON.stringify(status.missing)) + story;
    story += FOOTER[l](status.downloadedAt);
    writeFileSync(join(REPO_ROOT, PATHS.story[l]), story);
    console.log(`OK ${PATHS.story[l]}`);
  }
} catch (e) {
  console.error((e as Error).message);
  process.exit(1);
}
